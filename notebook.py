def normalize_turkish(text: str) -> str:
    """
    Evaluation için normalize eder.

    - Türkçe İ / I dönüşümünü açıkça yönetir
    - Büyük/küçük harf farkını kaldırır
    - Noktalama işaretlerini kaldırır
    - Fazla boşlukları temizler
    - Türkçe karakterleri korur

    NOT:
    Training transcriptlerini değiştirmiyoruz.
    Sadece WER/CER hesaplamasından önce normalize ediyoruz.
    """

    if text is None:
        return ""

    text = text.strip()

    # Unicode normalization
    text = unicodedata.normalize(
        "NFC",
        text
    )

    # Türkçe özel durumlar
    text = text.replace("İ", "i")
    text = text.replace("I", "ı")

    # Diğer karakterler için lowercase
    text = text.lower()

    # Unicode combining mark temizliği
    text = unicodedata.normalize(
        "NFC",
        text
    )

    # Noktalama işaretlerini kaldır
    text = "".join(
        char
        for char in text
        if not unicodedata.category(char).startswith("P")
    )

    # Fazla boşlukları temizle
    text = re.sub(
        r"\s+",
        " ",
        text
    ).strip()

    return text


