def transcribe(
    model,
    processor,
    audio_path
):

    audio, _ = librosa.load(
        str(audio_path),
        sr=16000,
        mono=True,
    )

    inputs = processor(
        audio,
        sampling_rate=16000,
        return_tensors="pt",
    )

    with torch.no_grad():

        ids = model.generate(
            inputs.input_features.to(device),

            language="turkish",
            task="transcribe",

            # Whisper special tokens için biraz boşluk bırakıyoruz
            max_new_tokens=444,

            # Önceki repetition problemini azalt
            repetition_penalty=1.1,
            no_repeat_ngram_size=3,
        )

    return processor.batch_decode(
        ids,
        skip_special_tokens=True,
    )[0].strip()


